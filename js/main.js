// i18n Logic
const getPreferredLanguage = () => {
  const urlParams = new URLSearchParams(window.location.search);
  const langParam = urlParams.get('lang')?.toLowerCase();

  const map = {
    'pt': 'pt', 'br': 'pt',
    'en': 'en', 'us': 'en', 'uk': 'en'
  };

  if (langParam) {
    const baseLang = langParam.split('-')[0];
    if (map[baseLang]) return map[baseLang];
    if (translations[baseLang]) return baseLang;
  }

  const saved = localStorage.getItem('preferred-lang');
  if (saved) return saved;
  const browserLang = navigator.language.split('-')[0];
  return translations[browserLang] ? browserLang : 'pt';
};

let currentLang = getPreferredLanguage();

const updateContent = (lang) => {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  // Update Hrefs
  document.querySelectorAll('[data-i18n-href]').forEach(el => {
    const key = el.getAttribute('data-i18n-href');
    if (translations[lang] && translations[lang][key]) {
      el.href = translations[lang][key];
    }
  });

  // Update Meta Tags
  if (translations[lang]) {
    document.title = translations[lang]['meta-title'];
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute('content', translations[lang]['meta-description']);
  }

  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';

  // Update switcher buttons state - using border and text colors
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('text-cyan-400', 'border-cyan-400');
      btn.classList.remove('text-slate-400', 'border-transparent');
    } else {
      btn.classList.remove('text-cyan-400', 'border-cyan-400');
      btn.classList.add('text-slate-400', 'border-transparent');
    }
  });
};

const setLanguage = (lang) => {
  currentLang = lang;
  localStorage.setItem('preferred-lang', lang);

  // Update URL with lang parameter
  const url = new URL(window.location.href);
  url.searchParams.set('lang', lang);
  window.history.pushState({}, '', url);

  updateContent(lang);
};

// Analytics Event Helper
const trackEvent = (eventName, eventParams = {}) => {
  try {
    if (typeof window.clarity === 'function') {
      window.clarity('event', eventName);
    }
    if (typeof window.gtag === 'function') {
      window.gtag('event', eventName, eventParams);
    }
  } catch (err) {
    console.debug('Analytics event error:', err);
  }
};

// Initialize
const init = () => {
  document.body.classList.add('loaded');
  updateContent(currentLang);

  // Scroll Reveal Observer
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('active');
        if (entry.target.querySelector('.counter-val')) {
          startCounters(entry.target);
        }
      }
    });
  }, { threshold: 0.1 });

  document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));

  // Fab Visibility
  const fab = document.getElementById('fab-cta');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 500) {
      fab.classList.add('visible');
    } else {
      fab.classList.remove('visible');
    }
  });

  // Glass Card Glow Effect
  document.addEventListener('mousemove', (e) => {
    document.querySelectorAll('.glass-card').forEach(card => {
      const rect = card.getBoundingClientRect();
      const x = ((e.clientX - rect.left) / rect.width) * 100;
      const y = ((e.clientY - rect.top) / rect.height) * 100;
      card.style.setProperty('--x', `${x}%`);
      card.style.setProperty('--y', `${y}%`);
    });
  });

  // Arbitrage Calculator Logic
  const calcInputs = ['current-salary', 'usd-rate', 'target-salary-usd'];
  calcInputs.forEach(id => {
    document.getElementById(id)?.addEventListener('input', () => {
      calculateArbitrage();
      trackEvent('calculator_interaction', { input: id });
    });
  });
  calculateArbitrage();

  // Delegation for language buttons
  document.addEventListener('click', (e) => {
    const btn = e.target.closest('.lang-btn');
    if (btn) {
      const lang = btn.getAttribute('data-lang');
      if (lang) {
        setLanguage(lang);
        trackEvent('language_changed', { language: lang });
      }
    }
  });

  // Track CTA clicks
  document.querySelectorAll('a[href*="hotmart"], a[href="#oferta"], #calc-cta-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const text = btn.innerText.trim();
      trackEvent('cta_click', { button_text: text, href: btn.getAttribute('href') });
    });
  });

  // Lead Forms Handling & Redirect to 7 Passos Simples Guide
  const setupLeadForm = (formId, sourceName) => {
    const form = document.getElementById(formId);
    if (!form) return;

    form.addEventListener('submit', (e) => {
      e.preventDefault();
      const emailInput = form.querySelector('input[type="email"]');
      const email = emailInput ? emailInput.value.trim() : '';

      trackEvent('lead_captured', { email: email, source: sourceName });

      try {
        localStorage.setItem('subscriber_email', email);
      } catch (err) {}

      // Open / redirect directly to the 7 Passos Simples guide
      window.location.href = 'https://robsoncassiano.software/7-passos-simples-dev-na-gringa';
    });
  };

  setupLeadForm('page-lead-form', 'landing_page_newsletter_section');
  setupLeadForm('exit-lead-form', 'exit_intent_modal');

  // Terms Modal Logic
  const openTermsBtn = document.getElementById('open-terms');
  const closeTermsBtn = document.getElementById('close-terms');
  const termsModal = document.getElementById('terms-modal');

  if (openTermsBtn && closeTermsBtn && termsModal) {
    openTermsBtn.addEventListener('click', (e) => {
      e.preventDefault();
      termsModal.classList.add('open');
      document.body.style.overflow = 'hidden'; // Prevent scrolling
      trackEvent('terms_opened');
    });

    closeTermsBtn.addEventListener('click', () => {
      termsModal.classList.remove('open');
      document.body.style.overflow = '';
    });

    termsModal.addEventListener('click', (e) => {
      if (e.target === termsModal) {
        termsModal.classList.remove('open');
        document.body.style.overflow = '';
      }
    });
  }

  // Exit Intent Modal Logic
  const exitModal = document.getElementById('exit-intent-modal');
  const closeExitBtn = document.getElementById('close-exit-modal');
  let exitIntentTriggered = sessionStorage.getItem('exit_modal_dismissed') === 'true';

  const showExitModal = () => {
    if (!exitIntentTriggered && exitModal) {
      exitModal.classList.add('open');
      document.body.style.overflow = 'hidden';
      exitIntentTriggered = true;
      sessionStorage.setItem('exit_modal_dismissed', 'true');
      trackEvent('exit_intent_modal_shown');
    }
  };

  const closeExitModal = () => {
    if (exitModal) {
      exitModal.classList.remove('open');
      document.body.style.overflow = '';
      sessionStorage.setItem('exit_modal_dismissed', 'true');
      trackEvent('exit_intent_modal_closed');
    }
  };

  if (exitModal && closeExitBtn) {
    // Desktop mouseleave top detection
    document.addEventListener('mouseleave', (e) => {
      if (e.clientY <= 20) {
        showExitModal();
      }
    });

    closeExitBtn.addEventListener('click', closeExitModal);

    exitModal.addEventListener('click', (e) => {
      if (e.target === exitModal) {
        closeExitModal();
      }
    });

    document.addEventListener('keydown', (e) => {
      if (e.key === 'Escape' && exitModal.classList.contains('open')) {
        closeExitModal();
      }
    });
  }
};

const calculateArbitrage = () => {
  const current = parseFloat(document.getElementById('current-salary')?.value) || 0;
  const rate = parseFloat(document.getElementById('usd-rate')?.value) || 0;
  const targetUsd = parseFloat(document.getElementById('target-salary-usd')?.value) || 0;

  const targetBrl = targetUsd * rate;
  const diff = targetBrl - current;

  const resultEl = document.getElementById('calc-result-value');
  if (resultEl) {
    resultEl.innerText = new Intl.NumberFormat('pt-BR', { style: 'currency', currency: 'BRL', maximumFractionDigits: 0 }).format(diff > 0 ? diff : 0);
  }
};

const startCounters = (parent) => {
  parent.querySelectorAll('.counter-val').forEach(counter => {
    const target = +counter.getAttribute('data-target');
    const duration = 2000;
    const increment = target / (duration / 16);
    let current = 0;

    const update = () => {
      current += increment;
      if (current < target) {
        counter.innerText = Math.ceil(current) + '+';
        requestAnimationFrame(update);
      } else {
        counter.innerText = target + '+';
      }
    };
    update();
  });
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', init);
} else {
  init();
}
